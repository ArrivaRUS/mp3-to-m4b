// WindowGeometry — «окно всегда целиком на экране», одним правилом на обе оси.
//
// Почему отдельный файл: правило раньше жило ДВУМЯ инлайн-копиями в AppDelegate
// (applyWindowWidth / refitWindowHeight), а проба-замер держала ТРЕТЬЮ копию.
// Копии расходятся — и замер перестаёт что-либо доказывать. Здесь оно одно,
// чистое (CGRect → CGRect, без AppKit и без NSWindow), поэтому его можно
// прогнать юнитом: app/selfcheck_routing.swift.
//
// Зачем оно вообще (два боевых бага, оба воспроизведены замером):
//   · по горизонтали — окно 400, припаркованное у правого края, при переходе на
//     окно подтверждения (640) уезжало за край на 240 pt: AppKit кадр по
//     горизонтали НЕ ограничивает, а там правая часть футера — кнопка «Собрать»;
//   · по вертикали — окно, стоящее низко, растёт ВНИЗ от приколотого верха, и
//     футер уходил под нижнюю границу экрана (замерено до 357 pt на книге с
//     большим числом глав). `cappedContentHeight` ограничивает ВЫСОТУ, но не
//     ПОЗИЦИЮ: «высота ≤ экрана» ещё не значит «окно на экране».
//
// Оси РАЗДЕЛЕНЫ намеренно, а не объединены в один clamp(frame): каждый вызов
// правит только ту ось, которую сам только что изменил. Окно, которое человек
// утащил вниз руками, мы не дёргаем — правим лишь то, что подвинули сами.
//
// Приоритет краёв в вырожденном случае (окно БОЛЬШЕ экрана) выбран осознанно и
// зафиксирован тестами:
//   · по вертикали — сначала низ, ПОТОМ верх: тайтлбар важнее футера, окно с
//     уехавшим низом можно утащить мышкой, окно с тайтлбаром под меню-баром —
//     уже нет;
//   · по горизонтали — сначала право, ПОТОМ лево: видно начало содержимого, а не
//     его хвост.
// На практике до вырожденного случая не доходит: высоту держит
// `cappedContentHeight`, ширина фиксирована макетом (400/640).

import CoreGraphics
import Foundation

extension Notification.Name {
    /// «Содержимое только что изменило высоту — переизмерь окно».
    ///
    /// Раскрывающийся блок (FDA-инструкция на карточке доступа, «Подробности» на
    /// экранах установки) меняет высоту содержимого ВНУТРИ SwiftUI, а высоту окна
    /// задаёт AppKit — и узнать об этом ему неоткуда. Без сигнала получается ровно
    /// то, что поймал Юрка: блок раскрылся, окно осталось прежним, текст обрезан на
    /// полуслове («…путь ляжет в буфер обме—»), а под окном пустует треть экрана.
    ///
    /// Это НЕ про потолок высоты (он считается от экрана и остаётся как есть) —
    /// это про то, что переизмерение никто не звал.
    static let mp3ContentHeightDidChange = Notification.Name("mp3tom4b.contentHeightDidChange")
}

enum WindowGeometry {

    /// Упёрлось ли содержимое в потолок — то есть будет ли прокрутка на самом деле.
    ///
    /// Нужно, чтобы обрезание было ВИДНО. Прокрутка, о которой не догадываешься, —
    /// это просто обрезанный текст: человек видит фразу, оборванную на полуслове, и
    /// считает это багом, а не приглашением прокрутить. Признак вычисляется из уже
    /// известных величин (желаемая высота против потолка), без самозамера через
    /// GeometryReader (.patches/002).
    static func contentOverflows(desired: CGFloat, cap: CGFloat) -> Bool {
        desired > cap + 0.5
    }

    /// Сдвинуть кадр по ГОРИЗОНТАЛИ ровно настолько, чтобы он поместился в
    /// `visible` (видимая область экрана). Размер не меняется. Кадр, который уже
    /// внутри, возвращается без изменений — двигаем, ТОЛЬКО если иначе вылезет.
    /// Если кадр шире экрана, побеждает ЛЕВЫЙ край (видно начало содержимого).
    static func clampedHorizontally(_ frame: CGRect, in visible: CGRect) -> CGRect {
        var out = frame
        if out.maxX > visible.maxX { out.origin.x = visible.maxX - out.width }
        if out.minX < visible.minX { out.origin.x = visible.minX }
        return out
    }

    /// Сдвинуть кадр по ВЕРТИКАЛИ ровно настолько, чтобы он поместился в
    /// `visible`. Размер не меняется; кадр, который уже внутри, не трогаем.
    /// Если кадр выше экрана, побеждает ВЕРХНИЙ край — тайтлбар остаётся
    /// доступен, и окно можно утащить мышкой.
    static func clampedVertically(_ frame: CGRect, in visible: CGRect) -> CGRect {
        var out = frame
        if out.minY < visible.minY { out.origin.y = visible.minY }
        if out.maxY > visible.maxY { out.origin.y = visible.maxY - out.height }
        return out
    }
}
