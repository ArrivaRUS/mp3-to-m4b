// WindowPresentation — «окно создано» ≠ «человек его видит»: лестница показа.
//
// Почему отдельный файл и почему ЧИСТЫЙ: решение «какой следующий шаг» обязано
// проверяться юнитом, а всё, что зовёт NSApp/NSWindow, юнитом не проверяется —
// результат активации на macOS 26 определяет политика WindowServer, а не наш код.
// Поэтому здесь ТОЛЬКО правило (булевы факты → следующая ступень), а сами вызовы
// AppKit живут в AppDelegate.presentWindow (app/main.swift). Ровно тот же приём и
// ровно по той же причине, что в app/WindowGeometry.swift: правило одно, оно
// видно целиком и его нельзя «слегка разойтись» с его же проверкой.
//
// Что чинит (боевой инцидент 2026-07-27, .patches/006, разобран по unified log):
// агент кладёт книгу → `open -b` → rc=0 → приложение стартует → окно создаётся за
// 0.6 с → и 85 секунд стоит ПОЛНОСТЬЮ ПЕРЕКРЫТОЕ чужим окном, пока человек сам не
// кликнет по приложению. macOS 26 (Tahoe) — кооперативная активация: у процесса,
// поднятого программно через LaunchServices, нулевой «кредит активации», и
// WindowServer отказывает прямым текстом:
//
//     CPS: The requested process (pid = 2770) presents 0 windows … Denying the request.
//     CPS: Rejecting the request for pid 2770 due to the activation count being 0;
//          … window count = 1.
//
// Первый отказ — LS-активация пришла раньше, чем окно создалось; второй — уже при
// живом окне, на наш собственный `NSApp.activate(ignoringOtherApps: true)`.
// Deprecated-флаг `ignoringOtherApps` на Tahoe — no-op.
//
// Цель лестницы намеренно сформулирована в ДОСТИЖИМЫХ терминах: «окно ВИДИМО, не
// перекрыто», а НЕ «окно забрало фокус». Гарантированно забрать фокус без действия
// человека на Tahoe невозможно — это политика ОС, а не наш баг (.patches/006,
// правило 4). Требование, сформулированное как «перехватить клавиатуру», чинилось
// бы вечно.

import Foundation

/// Ступень лестницы = ПОСЛЕДНЕЕ выполненное действие показа.
///
/// Порядок ступеней — по возрастанию вмешательства в работу человека: сначала то,
/// что он может не заметить, и только потом то, что дёргает его внимание.
enum PresentationStep: Equatable {
    /// База: `makeKeyAndOrderFront` + `NSApp.activate()`. Ровно то, что делалось и
    /// раньше — и что на Tahoe законно может не дать ничего.
    case ordered
    /// `window.orderFrontRegardless()` — санкционированный API: поднимает окно
    /// ПОВЕРХ окон чужих приложений, НЕ запрашивая активацию. Это и есть наш
    /// случай: активацию нам не дают, а видимость — не активация.
    case orderedRegardless
    /// `NSApp.requestUserAttention(.informationalRequest)` — РАЗОВЫЙ подскок иконки
    /// в доке. Последняя ступень: дальше идут только средства, которые перебивают
    /// работу человека (модальные панели, `.criticalRequest` с бесконечным
    /// подскоком), а окно подтверждения — не авария.
    case attentionRequested
    /// Лестница исчерпана либо не нужна: действий больше нет, ничего не заводится.
    case done
}

/// Итог самопроверки видимости.
enum PresentationOutcome: Equatable {
    /// Человек видит окно (или приложение вышло вперёд) — эскалацию гасим, таймеры
    /// отменяем, невыполненный запрос внимания снимаем.
    case satisfied
    /// Перейти на указанную ступень: выполнить её действие и, если у ступени есть
    /// задержка перепроверки, провериться снова. `.escalate(.done)` — «ступеней
    /// больше нет»: ноль действий, таймер не заводится, состояние терминальное.
    case escalate(PresentationStep)
}

enum WindowPresentation {

    /// Пауза перед первой самопроверкой, после базового показа.
    ///
    /// 1.0 с — это компромисс двух рисков, оба измерены на боевом инциденте:
    /// проверить РАНЬШЕ, чем WindowServer успел применить наш `orderFront`, значит
    /// эскалировать на ровном месте (лишний подскок дока при нормальном показе);
    /// проверить ПОЗЖЕ — значит подарить человеку ещё секунду пустого экрана.
    /// В инциденте окно родилось за 0.6 с от запроса LS, так что секунды хватает,
    /// чтобы факт видимости уже был окончательным.
    static let recheckAfterOrdered: TimeInterval = 1.0

    /// Пауза перед второй самопроверкой, после `orderFrontRegardless()`.
    ///
    /// Длиннее первой намеренно: следующая ступень — единственная ЗАМЕТНАЯ человеку
    /// (подскок иконки), и цена ложного срабатывания здесь выше, чем цена лишних
    /// полсекунды ожидания.
    static let recheckAfterOrderedRegardless: TimeInterval = 1.5

    /// Через сколько перепроверять видимость после того, как ступень выполнена.
    /// `nil` = ступень терминальная, перепроверять незачем: эскалировать всё равно
    /// некуда, а живой таймер без адресата — это ретейн, который некому погасить.
    static func recheckDelay(after step: PresentationStep) -> TimeInterval? {
        switch step {
        case .ordered:            return recheckAfterOrdered
        case .orderedRegardless:  return recheckAfterOrderedRegardless
        case .attentionRequested: return nil   // выше подниматься нечем
        case .done:               return nil   // терминал
        }
    }

    /// Решатель лестницы: по текущей ступени и двум фактам о реальности — что
    /// делать дальше. Чистая функция: одинаковый вход → одинаковый выход, никаких
    /// обращений к NSApp/NSWindow.
    ///
    /// ⚠️ ОСОЗНАННАЯ ГРАНИЦА, единственная в лестнице: `isActive` — КОСВЕННЫЙ
    /// признак успеха, и это ЕДИНСТВЕННОЕ место, где мы рапортуем «человек видит
    /// окно», не имея прямого доказательства (`isVisible`). Граница выбрана, а не
    /// проглядена, и вот почему её не сужаем:
    ///   · в боевом отказном сценарии (программный запуск, .patches/006) активация
    ///     ОТКЛОНЕНА — значит `isActive == false`, и на инциденте эта ветка вообще
    ///     не срабатывает: лестница судит по `isVisible`, как и задумано;
    ///   · если же приложение впереди — фокус нам ДАЛА сама ОС, то есть цель уже
    ///     достигнута более сильным способом, чем мы умеем просить.
    /// Убрать дизъюнкцию (предложение второго ревьюера) значит эскалировать у
    /// активного приложения в момент, когда occlusion ещё не пересчитан, — дёргать
    /// док у окна, на которое человек уже смотрит. Матрица 4×4 в сьюте закрывает
    /// оба флага во всех комбинациях; менять правило — только вместе с ней.
    ///
    /// - Parameters:
    ///   - step: ступень, действие которой уже выполнено.
    ///   - isActive: приложение вышло вперёд (`NSApp.isActive`).
    ///   - isVisible: хотя бы часть окна реально на экране
    ///     (`window.occlusionState.contains(.visible)`).
    static func next(after step: PresentationStep,
                     isActive: Bool,
                     isVisible: Bool) -> PresentationOutcome {
        // Критерий успеха — ДИЗЪЮНКЦИЯ, и это не небрежность.
        //   · isVisible — прямое доказательство цели: окно не перекрыто, не
        //     свёрнуто, не на чужом Space. Ради этого факта вся лестница и есть.
        //   · isActive — приложение впереди; его ключевое окно по определению не
        //     похоронено под чужим. Флаг нужен отдельно, потому что окно может стать
        //     активным раньше, чем система пересчитает occlusion, и эскалировать в
        //     этот момент значило бы дёрнуть док у уже показанного окна.
        // Отрицание этой дизъюнкции — ровно тот факт, что стоит за инцидентом:
        // приложение не впереди И окна не видно, то есть «показали» ничего не дало.
        if isActive || isVisible { return .satisfied }

        switch step {
        case .ordered:
            // Упорядочили и попросили активацию — не сработало. Отказ в АКТИВАЦИИ
            // не запрещает поднять окно: следующий шаг обходит именно ту политику,
            // которая нам отказала.
            return .escalate(.orderedRegardless)
        case .orderedRegardless:
            // Окно подняли поверх всех — и его всё равно не видно. Значит, дело уже
            // не в порядке окон (другой Space, полноэкранное чужое приложение,
            // выключенный дисплей). Средствами показа тут не помочь — остаётся
            // позвать человека туда, где он смотрит: иконка в доке.
            return .escalate(.attentionRequested)
        case .attentionRequested:
            // Человека позвали. Звать второй раз — это уже не забота, а навязчивость
            // (правило: разовый `.informationalRequest`, никогда не в цикле).
            return .escalate(.done)
        case .done:
            // Идемпотентный терминал: повторный вызов не порождает ни действий, ни
            // таймеров. Нужен, чтобы поздний тик отменённого таймера был безвреден.
            return .escalate(.done)
        }
    }
}
